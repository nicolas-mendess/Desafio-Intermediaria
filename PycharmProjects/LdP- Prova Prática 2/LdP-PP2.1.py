n1 = float(input("Digite o primeiro número: "))
n2 = float(input("Digite o segundo número: "))

print("Escolha a operação: [ + ] [ - ] [ * ] [ / ]")
op = input("Operação: ")
if op == '+' :
     n1 + n2
     print('Resultado:',n1 + n2)
elif op == '-':
     n1 - n2
     print('Resultado', n1 - n2)
elif op == '*':
     n1 * n2
     print('Resultado', n1 * n2)
elif op == '/':
     n1 / n2
     print('Resultado:', n1 / n2)
